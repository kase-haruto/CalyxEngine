#include "Button.h"

// engine

/////////////////////////////////////////////////////////////////////////////////////////
// ctor
/////////////////////////////////////////////////////////////////////////////////////////
Button::Button(const std::string& texturePath, const Vector2& pos, const Vector2& size)
	:pos_(pos), size_(size) {
	image_ = std::make_unique<Sprite>(texturePath);
	image_->Initialize(pos, size);
}

/////////////////////////////////////////////////////////////////////////////////////////
//		更新処理
/////////////////////////////////////////////////////////////////////////////////////////
void Button::Update([[maybe_unused]] float dt) {
	image_->Update();
}

/////////////////////////////////////////////////////////////////////////////////////////
//		実行関数のセット
/////////////////////////////////////////////////////////////////////////////////////////
void Button::SetOnExecute(std::function<void()> cb) {
	onExecute_ = cb;
}

/////////////////////////////////////////////////////////////////////////////////////////
//		実行
/////////////////////////////////////////////////////////////////////////////////////////
void Button::Execute() { if (onExecute_)onExecute_(); }

/////////////////////////////////////////////////////////////////////////////////////////
//		ボタンイメージ画像の取得
/////////////////////////////////////////////////////////////////////////////////////////
Sprite* Button::GetSprite() {
	if (!image_) return nullptr;

	return image_.get();
}

/////////////////////////////////////////////////////////////////////////////////////////
//		選択フラグ
/////////////////////////////////////////////////////////////////////////////////////////
void Button::SetSelected(bool selected) {
	isSelected_ = selected;
}

/////////////////////////////////////////////////////////////////////////////////////////
//		gui
/////////////////////////////////////////////////////////////////////////////////////////
void Button::ShowGui() {
	image_->ShowGui();
}


