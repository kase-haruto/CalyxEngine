#include "BulletFactory.h"

/////////////////////////////////////////////////////////////////////////////////////////
//		static object初期化
/////////////////////////////////////////////////////////////////////////////////////////
std::unordered_map<BulletID, BulletFactory::BulletCreator> BulletFactory::registry_;

/////////////////////////////////////////////////////////////////////////////////////////
//		弾の登録
/////////////////////////////////////////////////////////////////////////////////////////
void BulletFactory::Register(BulletID id, BulletCreator creator){
	registry_[id] = creator;
}

/////////////////////////////////////////////////////////////////////////////////////////
//		弾の生成
/////////////////////////////////////////////////////////////////////////////////////////
std::shared_ptr<BaseBullet> BulletFactory::Create(BulletID id){
	if (registry_.contains(id)){
		return registry_[id]();
	}
	return nullptr;
}
