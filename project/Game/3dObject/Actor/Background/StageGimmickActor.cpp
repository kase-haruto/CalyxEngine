#include "StageGimmickActor.h"

/////////////////////////////////////////////////////////////////////////////////////////
//		ctor / dtor
/////////////////////////////////////////////////////////////////////////////////////////
StageGimmickActor::StageGimmickActor()  = default;
StageGimmickActor::~StageGimmickActor() = default;

/////////////////////////////////////////////////////////////////////////////////////////
//		状態によって更新
/////////////////////////////////////////////////////////////////////////////////////////
void StageGimmickActor::Update(float dt) {
	// 状態遷移時の処理
	if(prevState_ != currentState_) {
		HandleStateTransition();
	}

	// 現在の状態に応じた更新
	ExecuteStateUpdate(dt);

	prevState_ = currentState_;
}

/////////////////////////////////////////////////////////////////////////////////////////
//		Stateの更新
/////////////////////////////////////////////////////////////////////////////////////////
void StageGimmickActor::ExecuteStateUpdate(float dt) {
	switch(currentState_) {
	case GimmickState::Idle:
		IdleUpdate(dt);
		break;
	case GimmickState::Running:
		RunningUpdate(dt);
		break;
	case GimmickState::Finished:
		OnFinished();
		break;
	}
}

/////////////////////////////////////////////////////////////////////////////////////////
//		State遷移の処理
/////////////////////////////////////////////////////////////////////////////////////////
void StageGimmickActor::HandleStateTransition() {
	if(currentState_ == GimmickState::Running) {
		OnTriggered();
	}
}

/////////////////////////////////////////////////////////////////////////////////////////
//		アイドル時更新
/////////////////////////////////////////////////////////////////////////////////////////
void StageGimmickActor::IdleUpdate(float dt) { (void)dt; }

/////////////////////////////////////////////////////////////////////////////////////////
//		トリガーされた瞬間の処理
/////////////////////////////////////////////////////////////////////////////////////////
void StageGimmickActor::OnTriggered() {}

/////////////////////////////////////////////////////////////////////////////////////////
//		動作中の処理
/////////////////////////////////////////////////////////////////////////////////////////
void StageGimmickActor::RunningUpdate(float dt) { (void)dt; }

/////////////////////////////////////////////////////////////////////////////////////////
//		動作終了時の処理
/////////////////////////////////////////////////////////////////////////////////////////
void StageGimmickActor::OnFinished() {}