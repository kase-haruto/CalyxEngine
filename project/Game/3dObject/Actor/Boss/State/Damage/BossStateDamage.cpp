#include "BossStateDamage.h"

#include "Game/3dObject/Actor/Boss/Anim/BossAnimController.h"
#include "Game/3dObject/Actor/Boss/Boss.h"
#include "Game/3dObject/Actor/Boss/Details/BossAnimType.h"

///////////////////////////////////////////////////////////////////////////////////////////
///		ctor / dtor
///////////////////////////////////////////////////////////////////////////////////////////
BossStateDamage::BossStateDamage() {
	BaseBossState::SetStatypeType(BossStateType::Damage);
}

BossStateDamage::~BossStateDamage() = default;

///////////////////////////////////////////////////////////////////////////////////////////
///		状態に入るときの処理
///////////////////////////////////////////////////////////////////////////////////////////
void BossStateDamage::Enter() {
	// ダメージアニメーション再生
	if(!owner_) return;
	if (BossAnimController* animator = owner_->GetAnimator()) {
		animator->Play(static_cast<int16_t>(BossAnimType::Damage));
	}
}

///////////////////////////////////////////////////////////////////////////////////////////
///		更新処理
///////////////////////////////////////////////////////////////////////////////////////////
void BossStateDamage::Update(float dt) {
	(void)dt;
	if(!owner_) return;
	if (BossAnimController* animator = owner_->GetAnimator()) {
		// ダメージアニメーションが終了したら待機状態へ遷移
		if (animator->IsAnimFinished()) RequestChange(BossStateType::Idle);
	}
}