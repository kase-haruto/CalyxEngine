#include "IBossState.h"

IBossState::IBossState()  = default;
IBossState::~IBossState() = default;

/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
const IBossState::TransitionRequest& IBossState::GetTransitionRequest() const {
	return request_;
}
BossStateType IBossState::GetStateType() const {
	return state_;
}

/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
void IBossState::RequestTransition(BossStateType nextType) {
	request_.hasRequest = true;
	request_.nextType	= nextType;
}