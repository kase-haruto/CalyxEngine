#include "BossStateDeath.h"

#include "Game/3dObject/Actor/Boss/Boss.h"
#include "Game/3dObject/Actor/Boss/Anim/BossAnimController.h"
#include "Game/3dObject/Actor/Boss/Details/BossAnimType.h"

///////////////////////////////////////////////////////////////////////////////////////////
///		ctor / dtor
///////////////////////////////////////////////////////////////////////////////////////////
BossStateDeath::BossStateDeath() { BaseBossState::SetStatypeType(BossStateType::Dead); }
BossStateDeath::~BossStateDeath() = default;

////////////////////////////////////////////////////////////////////////////////////////////
///		状態に入るときの処理
////////////////////////////////////////////////////////////////////////////////////////////
void BossStateDeath::Enter() {
	if(!owner_) return;
	// 待機アニメーション再生
	owner_->GetAnimator()->Play(static_cast<int16_t>(BossAnimType::Dead));
}

////////////////////////////////////////////////////////////////////////////////////////////
///		GUI表示
////////////////////////////////////////////////////////////////////////////////////////////
void BossStateDeath::ShowGui() { BaseBossState::ShowGui(); }